package com.tka;

public class Operators {
	
	public static void main (String[] args) {
		
		
		
		int a = 8;
		int b = 5;
		
		System.out.println("Arithmetic Operator \n ");
		System.out.println( "Addition --> " + a + " + " + b +" = " + (a+b));
		System.out.println( "Subtraction --> " + a + " - " + b +" = " + (a-b));
		System.out.println( "Multiplaction --> " + a + " * " + b +" = " + (a*b));
		System.out.println( "Division --> " + a + " / " + b +" = " + (a/b));
		System.out.println( "Moduls  --> " + a + " % " + b +" = " + (a%b));
		
		System.out.println("\n");
		
		System.out.println("Arithmetic Operator of 3 \n");
		System.out.println( "Addition of 3 --> " + (a+b+a));
		System.out.println( "Subtraction of 3 --> " + (a-b-a));
		System.out.println( "Multiplaction of 3 --> "  + (a*b*a));
		System.out.println( "Division of 3 --> " + (a/b/a));
		System.out.println( "Moduls of 3 --> "  + (a%b%a));
		
		//Relational / comparison  Operator
		
		int x = 8;
		int y = 9;
		
		System.out.println("\n");
		
		System.out.println("Comparsion operator\n");
		System.out.println( "Equals equals to --> " + a + " == " + b +" = " + (a==b));
		System.out.println( "Not equals to --> " + a + " != " + b +" = " + (a!=b));
		System.out.println( "Greater then --> " + a + " > " + b +" = " + (a>b));
		System.out.println( "Less than  --> " + a + " < " + b +" = " + (a<b));
		System.out.println( "Greater than equals to  --> " + a + " >= " + b +" = " + (a>=b));
		System.out.println( "Less than equals to  --> " + a + " <= " + b +" = " + (a<=b));
		
		
		
		
		
		
		
		
	}
	

}
